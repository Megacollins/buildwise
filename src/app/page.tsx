/** The landing page shows a real model generated by the same engine the app uses. */
function demo() {
  const sp = SAMPLE_PROJECTS[0];
  const region = REGIONS.find((r) => r.id === sp.regionId)!;
  const catalog = toRegionalCatalog(MATERIALS, region.id);
  const c = generateConcepts({ requirements: sp.requirements, plot: sp.plot, region, catalog, budget: sp.budget.target, selectionsForTier: defaultSelections })
    .find((x) => x.key === sp.conceptKey)!;
  return { sp, region, concept: c, colors: selectionColors(c.model, catalog) };
}

